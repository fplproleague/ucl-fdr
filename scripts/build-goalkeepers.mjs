// Regenerates src/data/goalkeepers.js — the FALLBACK snapshot shown to
// anyone whose browser can't reach the live sheet (ad-blocker, privacy
// extension, restrictive network) and while it loads. The live path is
// src/utils/useLiveGoalkeepers.js, which fetches the published sheet
// directly, so editing the sheet needs no rebuild for everyone else.
//
// Usage:
//   node scripts/build-goalkeepers.mjs
//     fetches the default published CSV URL below; fails on any bad row
//   node scripts/build-goalkeepers.mjs <url-or-local-csv-path>
//     fetches a different published CSV, or reads a local file (handy for
//     testing without network access — e.g. a CSV exported by hand)
//   node scripts/build-goalkeepers.mjs --soft
//     what `npm run build` runs (prebuild): refreshes the snapshot when it
//     can, but never fails the build — bad rows are skipped (exactly as the
//     live path skips them) and an unreachable sheet keeps the committed one
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildClubLookup, parseGoalkeeperRows } from '../src/utils/parseGoalkeepersCsv.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const { INITIAL_TEAMS } = await import('../src/data/teams.js')

const DEFAULT_SHEET_URL =
  'https://docs.google.com/spreadsheets/d/e/2PACX-1vT05F7C7W82oQEVdr3tSg_h5T3u3xXEh-FobEgnXwKvuGGWxwusdau5eeREapT28lRxgia51VVoXYPw/pub?gid=0&single=true&output=csv'

const args = process.argv.slice(2)
const soft = args.includes('--soft')
const source = args.find((a) => !a.startsWith('--')) ?? DEFAULT_SHEET_URL

async function readSource(src) {
  if (/^https?:\/\//.test(src)) {
    const res = await fetch(src, { signal: AbortSignal.timeout(15000) })
    if (!res.ok) throw new Error(`Failed to fetch ${src}: HTTP ${res.status}`)
    return res.text()
  }
  return readFileSync(src, 'utf8')
}

let raw
try {
  raw = await readSource(source)
} catch (err) {
  if (!soft) throw err
  console.warn(`GK snapshot: sheet unreachable, keeping the committed fallback — ${err.message}`)
  process.exit(0)
}

const { goalkeepers, errors } = parseGoalkeeperRows(raw, buildClubLookup(INITIAL_TEAMS))

console.log('goalkeepers parsed:', goalkeepers.length)
for (const e of errors) console.error(e)
console.log('all checks passed:', errors.length === 0)
if (!soft && errors.length) process.exit(1)
if (goalkeepers.length === 0) {
  console.warn('GK snapshot: no valid rows, keeping the committed fallback')
  process.exit(soft ? 0 : 1)
}

// Single-quoted, matching the rest of the codebase's style — not
// JSON.stringify, which would emit double quotes.
function quote(str) {
  return `'${str.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

const lines = goalkeepers
  .map((gk) => `  { id: '${gk.id}', name: ${quote(gk.name)}, team: '${gk.team}', price: ${gk.price} },`)
  .join('\n')

const out = `// GK Rotation FALLBACK database — shown when the live sheet can't be
// reached at runtime and while it loads (see
// src/utils/useLiveGoalkeepers.js, the actual live data path). Just the
// facts that don't already live elsewhere: name, the team they play for (a
// team abbreviation from src/data/teams.js), and their Fantasy price. Fixtures, matchdays, days and FDR are never
// duplicated here: every goalkeeper links to \`team\`, and everything about
// that team's schedule is read live from src/data/fixtures.js exactly like
// every other view in the app (see src/utils/teamComplement.js).
//
// Generated by scripts/build-goalkeepers.mjs from the published GK database
// Google Sheet — refreshed automatically on every deploy (prebuild); edits
// to the sheet take effect live for everyone who can reach it.
// Two goalkeepers can share a team (e.g. Inter, Napoli) — kept as separate
// records, never merged.
export const GOALKEEPERS = [
${lines}
]
`

writeFileSync(path.join(__dirname, '../src/data/goalkeepers.js'), out)
console.log('wrote src/data/goalkeepers.js')
