// Regenerates src/data/availability.js: which players UCL Fantasy flags as
// injured, doubtful, suspended or not in the UCL squad, from the game's own
// player feed. The site can't read that feed in the browser (UEFA only
// allows its own pages to), so this runs in the Availability GitHub Action
// and the result is committed, which redeploys the site.
//
// Usage:
//   node scripts/build-availability.mjs          fails loudly when the feed is down
//   node scripts/build-availability.mjs --soft   never fails: keeps the saved file
//
// The feed is unofficial and may change without notice. When it answers with
// no players, or far fewer than usual, the saved file is kept as it is.
// The file is only rewritten when a status changed, so a run with nothing
// new makes no commit (and no deploy).
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { availabilityFromFeed, feedMatchday } from '../src/utils/availability.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(__dirname, '../src/data/availability.js')
const soft = process.argv.includes('--soft')

// The same files the UCL Fantasy site itself loads: services/feeds/config/
// web.json names the season (tourId, 90 for 2026/27), and the player list
// is players_<tourId>_en_<matchday>.json. A matchday that isn't open yet
// answers 403, so the newest one that answers with players is the current
// one. (The services/api/Feed/players address used before started answering
// with an empty list.)
const ROOT = 'https://gaming.uefa.com/en/uclfantasy/services/feeds'
const HEADERS = { 'user-agent': 'ucl-fdr availability script' }
const LAST_MATCHDAY = 17
const MIN_PLAYERS = 500

async function getJson(url) {
  const res = await fetch(url, { headers: HEADERS, signal: AbortSignal.timeout(30000) })
  if (!res.ok) return { status: res.status }
  return { status: res.status, json: await res.json() }
}

async function tourId() {
  const { json } = await getJson(`${ROOT}/config/web.json`)
  const id = json?.data?.value?.tourId ?? JSON.stringify(json ?? {}).match(/"tourId":"?(\d+)/)?.[1]
  if (!id) throw new Error('no tourId in config/web.json')
  return id
}

async function newestList() {
  const tour = await tourId()
  const seen = []
  for (let md = LAST_MATCHDAY; md >= 1; md--) {
    const { status, json } = await getJson(`${ROOT}/players/players_${tour}_en_${md}.json`)
    const list = json?.data?.value?.playerList
    if (Array.isArray(list) && list.length >= MIN_PLAYERS) return { md: feedMatchday(list) || md, list }
    seen.push(`MD${md}: ${status}`)
  }
  throw new Error(`no player list for season ${tour} (${seen.slice(-3).join(', ')})`)
}

function savedPlayers() {
  try {
    const src = readFileSync(OUT, 'utf8')
    return JSON.stringify(Object.fromEntries([...src.matchAll(/(p[\w-]+): '([A-Z])'/g)].map((m) => [m[1], m[2]])))
  } catch {
    return null
  }
}

let feed
try {
  feed = await newestList()
} catch (err) {
  if (!soft) {
    console.error(`Availability: ${err.message}`)
    process.exit(1)
  }
  console.warn(`Availability: ${err.message}; keeping the saved file`)
  process.exit(0)
}

const players = availabilityFromFeed(feed.list)
const sorted = Object.fromEntries(Object.entries(players).sort(([a], [b]) => a.localeCompare(b)))
const counts = {}
for (const code of Object.values(sorted)) counts[code] = (counts[code] ?? 0) + 1
console.log(`Availability: ${feed.list.length} players in the feed (MD${feed.md}), flagged:`, counts)

if (JSON.stringify(sorted) === savedPlayers()) {
  console.log('Availability unchanged')
  process.exit(0)
}

const body = Object.entries(sorted)
  .map(([id, code]) => `    ${id}: '${code}',`)
  .join('\n')

writeFileSync(
  OUT,
  `// Player availability from UCL Fantasy: I injured, U doubtful and unlikely
// to start, D doubtful, S suspended, N not in the UCL squad (see
// src/utils/availability.js). Fit players have no entry. Generated by
// scripts/build-availability.mjs, refreshed by the Availability GitHub Action.
export const AVAILABILITY = {
  updated: '${new Date().toISOString().slice(0, 16)}Z',
  md: ${feed.md},
  players: {
${body}
  },
}
`,
)
console.log(`Availability: wrote ${Object.keys(sorted).length} players`)
