// Regenerates src/data/players.js — the FALLBACK snapshot of the player
// sheet, for anyone whose browser can't reach it (see
// src/utils/useLivePlayers.js for the live path).
//
// Usage:
//   node scripts/build-players.mjs                  the sheet in PLAYERS_SHEET_URL
//   node scripts/build-players.mjs <url-or-csv>     another sheet, or a local CSV
//   node scripts/build-players.mjs --soft           what `npm run build` runs:
//     never fails the build; does nothing while no sheet is configured
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildClubLookup } from '../src/utils/parseGoalkeepersCsv.js'
import { parsePlayerRows } from '../src/utils/parsePlayersCsv.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const { INITIAL_TEAMS } = await import('../src/data/teams.js')

// The URL lives in useLivePlayers.js (one place to paste it). That module
// imports React, so read the constant out of the source instead.
const hookSrc = readFileSync(path.join(__dirname, '../src/utils/useLivePlayers.js'), 'utf8')
const configured = hookSrc.match(/PLAYERS_SHEET_URL\s*=\s*\n?\s*'([^']+)'/)?.[1] ?? null

const args = process.argv.slice(2)
const soft = args.includes('--soft')
const source = args.find((a) => !a.startsWith('--')) ?? configured

if (!source) {
  console.log('Player snapshot: no sheet configured yet (PLAYERS_SHEET_URL), skipping')
  process.exit(0)
}

async function readSource(src) {
  if (/^https?:\/\//.test(src)) {
    const res = await fetch(src, { signal: AbortSignal.timeout(15000) })
    if (!res.ok) throw new Error(`Failed to fetch ${src}: HTTP ${res.status}`)
    return res.text()
  }
  return readFileSync(src, 'utf8')
}

let raw
try {
  raw = await readSource(source)
} catch (err) {
  if (!soft) throw err
  console.warn(`Player snapshot: sheet unreachable, keeping the committed fallback — ${err.message}`)
  process.exit(0)
}

const { players, errors } = parsePlayerRows(raw, buildClubLookup(INITIAL_TEAMS))
console.log('players parsed:', players.length)
for (const e of errors) console.error(e)
if (!soft && errors.length) process.exit(1)
if (players.length === 0) {
  console.warn('Player snapshot: no valid rows, keeping the committed fallback')
  process.exit(soft ? 0 : 1)
}

// A JS literal in the codebase's style (single quotes, bare keys) rather
// than JSON, one player per line. Handles the optional fields too (form,
// stats), which are plain numbers, arrays and objects.
const quote = (str) => `'${str.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
function toJs(value) {
  if (typeof value === 'string') return quote(value)
  if (Array.isArray(value)) return `[${value.map(toJs).join(', ')}]`
  if (value && typeof value === 'object')
    return `{ ${Object.entries(value)
      .map(([k, v]) => `${k}: ${toJs(v)}`)
      .join(', ')} }`
  return String(value)
}
const lines = players.map((p) => `  ${toJs(p)},`).join('\n')

writeFileSync(
  path.join(__dirname, '../src/data/players.js'),
  `// Player database FALLBACK for the Players tab — shown when the live sheet
// can't be reached (the live path is src/utils/useLivePlayers.js, which
// loads this file only when the tab opens). Generated by
// scripts/build-players.mjs from the published player sheet, refreshed on
// every deploy.
export const PLAYERS = [
${lines}
]
`,
)
console.log('wrote src/data/players.js')
